// ABI pipeline.
//
//   node --experimental-strip-types scripts/gen-abis.ts import <path-to-nablaz-protocol>
//     Copies the `abi` array (and nothing else) out of nablaz-protocol's forge build output into
//     abis/<Contract>.json and records the source commit in abis/PROVENANCE.json. Run `forge build`
//     in the protocol checkout first. Not run in CI: CI has no access to nablaz-protocol.
//
//   node --experimental-strip-types scripts/gen-abis.ts ts
//     Regenerates src/generated/abis.ts from abis/*.json (typed `as const` for Ponder). CI runs this
//     and fails on any diff, so the TypeScript never drifts from the JSON.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const CONTRACTS = [
  "NablaRecord",
  "NablaAccountFactoryPermanent",
  "AccountRegistryV6",
  "ConsumerAIMandateV4",
  "GranteeVault",
  "NablaAccountV3",
] as const;

const [mode, proto] = process.argv.slice(2);

if (mode === "import") {
  if (!proto) throw new Error("usage: gen-abis.ts import <path-to-nablaz-protocol>");
  const sha = execFileSync("git", ["-C", proto, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
  const dirty = execFileSync("git", ["-C", proto, "status", "--porcelain", "--", "src"], { encoding: "utf8" });
  if (dirty.trim() !== "") throw new Error("nablaz-protocol src/ has local changes");
  const forge = execFileSync("forge", ["--version"], { encoding: "utf8" }).split("\n")[0]!.trim();
  for (const name of CONTRACTS) {
    const artifact = JSON.parse(readFileSync(join(proto, "out", `${name}.sol`, `${name}.json`), "utf8"));
    if (!Array.isArray(artifact.abi)) throw new Error(`${name}: no abi`);
    writeFileSync(join("abis", `${name}.json`), `${JSON.stringify(artifact.abi, null, 2)}\n`);
  }
  const provenance = { source: "nablaz-protocol forge build output (abi field only)", protoSha: sha, forge, contracts: CONTRACTS };
  writeFileSync(join("abis", "PROVENANCE.json"), `${JSON.stringify(provenance, null, 2)}\n`);
  console.log(`imported ${CONTRACTS.length} ABIs from ${sha}`);
} else if (mode !== "ts") {
  throw new Error("usage: gen-abis.ts import <proto> | ts");
}

const provenance = JSON.parse(readFileSync(join("abis", "PROVENANCE.json"), "utf8"));
let ts = `// GENERATED by scripts/gen-abis.ts from abis/*.json — do not edit.\n`;
ts += `// ABIs from nablaz-protocol ${provenance.protoSha} (${provenance.forge}).\n`;
ts += `export const ABI_PROTO_SHA = "${provenance.protoSha}" as const;\n`;
for (const name of CONTRACTS) {
  const abi = readFileSync(join("abis", `${name}.json`), "utf8").trim();
  ts += `\nexport const ${name}Abi = ${abi} as const;\n`;
}
writeFileSync(join("src", "generated", "abis.ts"), ts);
