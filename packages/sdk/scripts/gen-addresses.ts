// Generates src/generated/addresses.ts from nablaz-protocol's script/expected/permanent-arbitrum.txt.
//
//   node --experimental-strip-types scripts/gen-addresses.ts <path-to-nablaz-protocol>
//
// Reads only the address list (public on chain) and the checkout's commit sha. The start block for each
// contract is its deployment block, found by binary search on eth_getCode through READER_ARB_RPC_URL.
// Not run in CI: CI has no access to nablaz-protocol. The header records the sha for review.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { createPublicClient, getAddress, http, type Address } from "viem";

const SOURCE = "script/expected/permanent-arbitrum.txt";
// "live": what ProtocolConfig and new accounts use. "coexisting": still deployed and still in the manifest,
// kept so old logs decode; never a payment target (R-S184-5). A vault's implementation is always read from
// its account (VAULT_IMPL()), never from this table.
const WANTED = {
  NablaRecord: "live",
  NablaAccountFactoryPermanent: "live",
  AccountRegistryV6: "live",
  ConsumerAIMandateV4: "live",
  GranteeVaultV2: "live",
  NablaAccountV3_1: "live",
  GranteeVault: "coexisting",
  NablaAccountV3: "coexisting",
} as const;

const proto = process.argv[2];
if (!proto) throw new Error("usage: gen-addresses.ts <path-to-nablaz-protocol>");
const rpc = process.env.READER_ARB_RPC_URL;
if (!rpc) throw new Error("READER_ARB_RPC_URL unset");

const sha = execFileSync("git", ["-C", proto, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
const dirty = execFileSync("git", ["-C", proto, "status", "--porcelain", "--", SOURCE], { encoding: "utf8" });
if (dirty.trim() !== "") throw new Error(`${SOURCE} has local changes`);

const lines = readFileSync(join(proto, SOURCE), "utf8").split("\n");
const found = new Map<string, Address>();
let chainId: number | undefined;
for (const line of lines) {
  const [name, value] = line.trim().split(/\s+/);
  if (name === "chainId") chainId = Number(value);
  else if (name && value?.startsWith("0x")) found.set(name, getAddress(value));
}
if (chainId !== 42161) throw new Error(`expected chainId 42161, got ${chainId}`);

const client = createPublicClient({ transport: http(rpc) });
const head = await client.getBlockNumber();

async function deployBlock(address: Address): Promise<bigint> {
  const has = async (b: bigint) => ((await client.getCode({ address, blockNumber: b })) ?? "0x") !== "0x";
  if (!(await has(head))) throw new Error(`${address} has no code at head`);
  let lo = 0n;
  let hi = head;
  while (lo < hi) {
    const mid = (lo + hi) / 2n;
    if (await has(mid)) hi = mid;
    else lo = mid + 1n;
  }
  return lo;
}

const rows: string[] = [];
for (const [name, status] of Object.entries(WANTED)) {
  const address = found.get(name);
  if (!address) throw new Error(`${name} missing from ${SOURCE}`);
  const block = await deployBlock(address);
  rows.push(`    ${name}: { address: "${address}", deployBlock: ${block}, status: "${status}" },`);
}

const out = `// GENERATED by scripts/gen-addresses.ts — do not edit.
// Source: nablaz-protocol ${SOURCE} at ${sha}
// deployBlock: first block with code at the address (binary search on eth_getCode, head ${head}).
// status "coexisting": deployed and in the manifest, never a payment target (R-S184-5).
export const PROTO_SHA = "${sha}" as const;

export const ARBITRUM_ONE = {
  chainId: 42161,
  contracts: {
${rows.join("\n")}
  },
} as const;

/** Vault implementations that must never be a payment target. */
export const NEVER_PAYMENT_TARGET: readonly string[] = [ARBITRUM_ONE.contracts.GranteeVault.address];
`;
writeFileSync("src/generated/addresses.ts", out);
console.log(`wrote src/generated/addresses.ts from ${sha}`);
